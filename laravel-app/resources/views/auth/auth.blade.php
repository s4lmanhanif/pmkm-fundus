    const tabs = document.querySelectorAll('[data-tab]');
    const forms = document.querySelectorAll('[data-form]');
    tabs.forEach(tab => {
        tab.addEventListener('click', () => {
            tabs.forEach(t => t.classList.remove('bg-primary','text-white','shadow-sm'));
            tabs.forEach(t => t.classList.add('text-slate-500'));
            tab.classList.add('bg-primary','text-white','shadow-sm');
            tab.classList.remove('text-slate-500');
            const target = tab.getAttribute('data-tab');
            forms.forEach(f => f.classList.add('hidden'));
            const active = document.querySelector(`[data-form="${target}"]`);
            active?.classList.remove('hidden');
        });
    });
